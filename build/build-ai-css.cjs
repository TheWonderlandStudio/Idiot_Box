// Builds the AI panel's scoped Tailwind stylesheet (AI Elements + shadcn)
// and embeds it as a JS string module for Shadow DOM injection.
// Output (ai-tw-css.js) is gitignored — rebuilt by `npm run build:ai-css`.
const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const input = path.join(root, "electron", "renderer", "components", "AIPanel", "ai-input.css");
const tmpCss = path.join(root, "electron", "renderer", "components", "AIPanel", "ai-tw.css");
const outJs = path.join(root, "electron", "renderer", "components", "AIPanel", "ai-tw-css.js");
const cli = path.join(root, "node_modules", "@tailwindcss", "cli", "dist", "index.mjs");

if (!fs.existsSync(cli)) {
  console.error("[build:ai-css] @tailwindcss/cli not found — run `npm install` (devDependencies).");
  process.exit(1);
}

const r = spawnSync(process.execPath, [cli, "-i", input, "-o", tmpCss], {
  cwd: root,
  stdio: "inherit",
  shell: false,
});
if (r.status !== 0) {
  console.error("[build:ai-css] tailwindcss build failed with code", r.status);
  process.exit(r.status || 1);
}

const css = fs.readFileSync(tmpCss, "utf8");
fs.writeFileSync(
  outJs,
  "// GENERATED by build/build-ai-css.cjs — do not edit. Rebuild with `npm run build:ai-css`.\n" +
    "export default " +
    JSON.stringify(css) +
    ";\n"
);
try { fs.unlinkSync(tmpCss); } catch {}
console.log(`[build:ai-css] wrote ai-tw-css.js (${(css.length / 1024).toFixed(1)} KB css)`);
