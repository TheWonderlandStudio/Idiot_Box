#!/usr/bin/env node
/**
 * Generate electron/renderer/theme/tokens.generated.js from variables.css.
 *
 * variables.css is the single source of truth for every color in the app.
 * This script turns it into a machine-readable token list so the Settings →
 * Appearance page can render a color picker for each token without keeping a
 * second hand-maintained copy of the palette.
 *
 * Run: node tools/generate-theme-tokens.cjs
 */
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(__dirname, "..")
const cssFile = path.join(root, "electron", "renderer", "variables.css")
const outFile = path.join(root, "electron", "renderer", "theme", "tokens.generated.js")

const css = fs.readFileSync(cssFile, "utf8")

// ── Parse :root / :root[data-theme="light"] blocks ──────────────────────────
const blockRe = /(:root(?:\[data-theme="(light|dark)"\])?)\s*\{([\s\S]*?)\n\}/g
const dark = new Map()
const light = new Map()
const meta = new Map() // key -> { comment, order }

let block
while ((block = blockRe.exec(css)) !== null) {
  const selector = block[1]
  const mode = block[2] === "light" ? "light" : "dark"
  const body = block[3]
  const declRe = /(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);([^\n]*)/g
  let decl
  while ((decl = declRe.exec(body)) !== null) {
    const key = decl[1]
    const value = decl[2].trim()
    const comment = (decl[3].match(/\/\*\s*(.*?)\s*\*\//) || [])[1] || ""
    if (!meta.has(key)) meta.set(key, { comment, order: meta.size })
    if (mode === "light") light.set(key, value)
    else dark.set(key, value)
  }
}

const COLOR_RE =
  /^(#[0-9a-fA-F]{3,8}|rgba?\(\s*[^)]*\)|hsla?\(\s*[^)]*\)|oklch\(\s*[^)]*\)|color\(\s*[^)]*\))$/

function isColor(value) {
  return COLOR_RE.test(String(value).trim())
}

// ── Grouping ───────────────────────────────────────────────────────────────
const GROUP_RULES = [
  [/^--bg-|^--paper|^--canvas-veil|^--coal$|^--black$|^--ink-on-teal$/, "surfaces", "Surfaces"],
  [/^--text-/, "text", "Text"],
  [/^--border-/, "borders", "Borders"],
  [/^--accent|^--editor-blue|^--select-blue|^--link-blue/, "accent", "Accent & links"],
  [/^--teal/, "teal", "Teal / live"],
  [/^--code-|^--info-/, "code", "Code & info"],
  [/^--git-|^--diff-/, "git", "Git & diff"],
  [/^--danger|^--error-/, "danger", "Danger & errors"],
  [/^--warn/, "warning", "Warnings"],
  [/^--success-/, "success", "Success"],
  [/^--selection|^--scrollbar|^--icon|^--overlay|^--white-a|^--away-|^--offline-/, "overlays", "Overlays & selection"],
  [/^--term-/, "terminal", "Terminal"],
  [/^--updater-|^--modal-/, "updater", "Updater & modals"],
  [/^--media-/, "media", "Media viewer"],
]

function groupFor(key) {
  for (const [re, id, label] of GROUP_RULES) {
    if (re.test(key)) return { id, label }
  }
  return { id: "misc", label: "Other component colors" }
}

function labelFor(key) {
  const base = key.replace(/^--/, "")
  const stripped = base
    .replace(/^(bg|text|border|accent|editor-blue|select-blue|link-blue|teal|code|info|git|diff|danger|error|warn|warning|success|selection|scrollbar|icon|overlay|white|term|updater|modal|media|paper|canvas)-?/, "")
  const words = (stripped || base).split("-").filter(Boolean)
  const text = words.join(" ")
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : base
}

const tokens = []
for (const [key, darkValue] of dark.entries()) {
  if (!isColor(darkValue)) continue
  const lightValue = light.get(key) || darkValue
  const { id, label } = groupFor(key)
  tokens.push({
    key,
    label: labelFor(key),
    group: id,
    groupLabel: label,
    dark: darkValue,
    light: lightValue,
    description: meta.get(key)?.comment || "",
  })
}

// Stable order: groups in first-seen order, tokens in CSS order.
const groups = []
const seen = new Map()
for (const token of tokens) {
  if (!seen.has(token.group)) {
    const entry = { id: token.group, label: token.groupLabel, tokens: [] }
    seen.set(token.group, entry)
    groups.push(entry)
  }
  seen.get(token.group).tokens.push(token.key)
}

const banner = `// AUTO-GENERATED by tools/generate-theme-tokens.cjs — do not edit by hand.
// Source of truth: electron/renderer/variables.css
// Regenerate with: npm run build:theme
`
const body = `${banner}
export const THEME_GROUPS = ${JSON.stringify(groups, null, 2)}

export const THEME_TOKENS = ${JSON.stringify(tokens, null, 2)}

export const THEME_TOKEN_MAP = Object.fromEntries(THEME_TOKENS.map((t) => [t.key, t]))

export const THEME_MODES = ["dark", "light"]
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, body)
console.log(`theme tokens: ${tokens.length} colors in ${groups.length} groups -> ${path.relative(root, outFile)}`)
